"""Verify every intra-page anchor link in the built documentation site.

``mkdocs build --strict`` fails on broken *page-level* links (a link to a
page that does not exist) but it does **not** validate the fragment: a
link to ``../guide/dates-and-conventions/#a-heading-that-was-renamed``
builds clean even though the anchor is gone.  Renaming a heading is
therefore a silent breakage, and headings get renamed often because the
docs carry the coverage matrix and the roadmap.

This script closes that gap.  It walks the *built* site, collects every
``id="..."`` present on each page, then re-reads each page and checks
that every ``href`` carrying a ``#fragment`` resolves to an anchor that
actually exists on the target page.  Page-level links are skipped --
``--strict`` already guards those, and duplicating the check here would
only produce confusing double failures.

Usage::

    mkdocs build --strict
    python scripts/check_doc_anchors.py

Exits non-zero (and prints one ``BROKEN`` line per bad link) if any
anchor is dangling, so it can be dropped into CI next to ``pytest``.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

#: Matches ``id="..."`` attributes, which is how MkDocs/Material emits
#: heading anchors (``<h2 id="business-day-calendars">``).
ID_PATTERN = re.compile(r'id="([^"]+)"')

#: Matches an ``href`` that contains a fragment.  The optional leading
#: ``../`` runs are kept in the capture so the target can be resolved
#: relative to the linking page's own directory.
HREF_PATTERN = re.compile(r'href="((?:\.\./)*[^":#]*#[^"]+)"')

#: Footnote back-references are generated by the footnotes extension and
#: point at ids synthesised at render time; they are not authored links.
SKIPPED_ANCHOR_PREFIXES = ("fnref",)


def collect_ids(pages: dict[Path, str]) -> dict[Path, set[str]]:
    """Collect the set of anchor ids defined on each built page.

    Args:
        pages: Mapping of resolved page path to that page's HTML.

    Returns:
        Mapping of resolved page path to the anchor ids it defines.
    """
    return {path: set(ID_PATTERN.findall(html)) for path, html in pages.items()}


def resolve_target(page: Path, path_part: str) -> Path:
    """Resolve a link's path component against the linking page.

    Args:
        page: Resolved path of the page containing the link.
        path_part: The ``href`` with the fragment stripped off.  Empty
            for a same-page link such as ``href="#greeks"``.

    Returns:
        The resolved path of the page the link points at.
    """
    if not path_part:
        return page
    target = (page.parent / path_part).resolve()
    return target / "index.html" if target.is_dir() else target


def check_site(site: Path) -> tuple[int, int]:
    """Check every anchored link in a built site.

    Args:
        site: Path to the built site directory (MkDocs' ``site/``).

    Returns:
        A tuple of (total anchored links checked, number broken).
    """
    pages = {
        path.resolve(): path.read_text(encoding="utf-8", errors="ignore")
        for path in sorted(site.rglob("*.html"))
    }
    ids = collect_ids(pages)

    total = broken = 0
    for page, html in pages.items():
        for href in HREF_PATTERN.findall(html):
            path_part, _, anchor = href.partition("#")
            if not anchor or anchor.startswith(SKIPPED_ANCHOR_PREFIXES):
                continue
            target = resolve_target(page, path_part)
            if target not in ids:
                # Page-level link, or a link out to an external/asset
                # path.  ``mkdocs build --strict`` owns that check.
                continue
            total += 1
            if anchor not in ids[target]:
                broken += 1
                print(f"BROKEN {page.relative_to(site.resolve())} -> {href}")
    return total, broken


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "site",
        nargs="?",
        default="site",
        type=Path,
        help="Path to the built site directory (default: ./site).",
    )
    args = parser.parse_args()

    site = args.site
    if not site.is_dir():
        print(
            f"error: {site} is not a directory; run `mkdocs build --strict` first.",
            file=sys.stderr,
        )
        return 2

    total, broken = check_site(site)
    pages = len(list(site.rglob("*.html")))
    print(f"{total} anchored links across {pages} pages; {broken} broken")
    return 1 if broken else 0


if __name__ == "__main__":
    raise SystemExit(main())
